"""Markdown and JSON report generation for a completed or in-progress
assessment."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from sentinel.schemas import Assessment
from sentinel.state_store import StateStore


def _gather(assessment: Assessment, store: StateStore) -> dict:
    return {
        "assessment": assessment.model_dump(mode="json"),
        "services": [s.model_dump(mode="json") for s in store.list_services(assessment.assessment_id)],
        "hypotheses": [h.model_dump(mode="json") for h in store.list_hypotheses(assessment.assessment_id)],
        "findings": [f.model_dump(mode="json") for f in store.list_findings(assessment.assessment_id)],
        "invocations": [i.model_dump(mode="json") for i in store.list_invocations(assessment.assessment_id)],
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }


def generate_json_report(assessment: Assessment, store: StateStore, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{assessment.assessment_id}.json"
    data = _gather(assessment, store)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    return path


def generate_markdown_report(assessment: Assessment, store: StateStore, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{assessment.assessment_id}.md"
    data = _gather(assessment, store)

    lines: list[str] = []
    lines.append(f"# Sentinel Assessment Report — {assessment.target}")
    lines.append("")
    lines.append(f"- **Assessment ID:** {assessment.assessment_id}")
    lines.append(f"- **Phase:** {assessment.phase.value}")
    lines.append(f"- **Status:** {assessment.status}")
    lines.append(f"- **Created:** {assessment.created_at.isoformat()}")
    lines.append(f"- **Iterations used:** {assessment.iteration_count}/{assessment.max_iterations}")
    lines.append("")

    lines.append("## Discovered Services")
    if data["services"]:
        lines.append("")
        lines.append("| Host | Port | Protocol | Service | Product/Version |")
        lines.append("|---|---|---|---|---|")
        for s in data["services"]:
            pv = " / ".join(x for x in [s.get("product"), s.get("version")] if x)
            lines.append(f"| {s['host']} | {s['port']} | {s['protocol']} | {s.get('service_name') or '-'} | {pv or '-'} |")
    else:
        lines.append("_No services recorded yet._")
    lines.append("")

    lines.append("## Investigation Timeline")
    lines.append("")
    if data["invocations"]:
        lines.append("| # | Tool | Operation | Exit Code | Timed Out |")
        lines.append("|---|---|---|---|---|")
        for idx, inv in enumerate(data["invocations"], start=1):
            lines.append(f"| {idx} | {inv['tool_name']} | {inv['operation']} | {inv.get('exit_code')} | {inv.get('timed_out')} |")
    else:
        lines.append("_No tool invocations recorded yet._")
    lines.append("")

    lines.append("## Hypotheses Tested")
    lines.append("")
    if data["hypotheses"]:
        for h in data["hypotheses"]:
            lines.append(f"- **[{h['status'].upper()}]** {h['description']}")
            if h.get("rationale"):
                lines.append(f"  - Rationale: {h['rationale']}")
    else:
        lines.append("_No hypotheses recorded yet._")
    lines.append("")

    lines.append("## Findings")
    lines.append("")
    confirmed = [f for f in data["findings"] if f["verification_status"] == "confirmed"]
    unresolved = [f for f in data["findings"] if f["verification_status"] != "confirmed"]

    lines.append("### Confirmed")
    if confirmed:
        for f in confirmed:
            lines.append(f"- **[{f['severity'].upper()}] {f['title']}** (confidence {f['confidence']:.2f})")
            lines.append(f"  - {f['description']}")
            if f.get("remediation"):
                lines.append(f"  - Remediation: {f['remediation']}")
    else:
        lines.append("_None confirmed yet._")
    lines.append("")

    lines.append("### Unresolved / Unverified")
    if unresolved:
        for f in unresolved:
            lines.append(f"- **[{f['verification_status']}] {f['title']}** (confidence {f['confidence']:.2f})")
            lines.append(f"  - {f['description']}")
    else:
        lines.append("_None._")
    lines.append("")

    lines.append("---")
    lines.append(f"_Generated by Sentinel at {data['generated_at']}._")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path
